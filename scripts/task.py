#!/usr/bin/env python3
"""Task board for docintel.

Stdlib only. board.json is the status. This script is the only writer.
"""

from __future__ import annotations

import argparse
import json
import sys
from contextlib import contextmanager
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUSES = ("pending", "ready", "in_progress", "blocked", "done")


class TaskError(Exception):
    pass


def now_stamp() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def repo_root(board: Path) -> Path:
    return board.resolve().parent


@contextmanager
def locked(board: Path):
    import fcntl

    lock_path = board.with_name(board.name + ".lock")
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    with lock_path.open("a+") as handle:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def load(board: Path) -> dict:
    try:
        data = json.loads(board.read_text())
    except FileNotFoundError as exc:
        raise TaskError(f"missing board: {board}") from exc
    ids = [task["id"] for task in data["tasks"]]
    if len(ids) != len(set(ids)):
        raise TaskError("duplicate task id in board.json")
    known = set(ids)
    for task in data["tasks"]:
        if task["status"] not in STATUSES:
            raise TaskError(f"{task['id']} has unknown status {task['status']}")
        missing = [dep for dep in task["depends_on"] if dep not in known]
        if missing:
            raise TaskError(f"{task['id']} depends on unknown tasks: {', '.join(missing)}")
    return data


def save(board: Path, data: dict) -> None:
    data["updated"] = datetime.now(UTC).date().isoformat()
    board.write_text(json.dumps(data, indent=2) + "\n")


def task_map(data: dict) -> dict[str, dict]:
    return {task["id"]: task for task in data["tasks"]}


def promote(data: dict) -> None:
    done = {task["id"] for task in data["tasks"] if task["status"] == "done"}
    for task in data["tasks"]:
        if task["status"] == "pending" and all(dep in done for dep in task["depends_on"]):
            task["status"] = "ready"


def add_note(task: dict, agent: str, text: str) -> None:
    task.setdefault("notes", []).append({"at": now_stamp(), "agent": agent, "text": text})


def require(data: dict, task_id: str) -> dict:
    found = task_map(data).get(task_id)
    if found is None:
        raise TaskError(f"unknown task {task_id}")
    return found


def render_now(data: dict) -> str:
    def lines_for(status: str) -> list[str]:
        chosen = [task for task in data["tasks"] if task["status"] == status]
        if not chosen:
            return ["- none"]
        rendered = []
        for task in chosen:
            extra = ""
            if status == "in_progress" and task.get("claimed_by"):
                extra = f" — {task['claimed_by']}"
            if status == "blocked" and task.get("notes"):
                extra = f" — {task['notes'][-1]['text']}"
            rendered.append(
                f"- {task['id']} — {task['title']} ({task['estimate_min']}m){extra}"
            )
        return rendered

    ready = [task for task in data["tasks"] if task["status"] == "ready"]
    if ready:
        first = ready[0]
        nxt = (
            f"{first['id']} — {first['title']} ({first['estimate_min']}m)\n\n"
            f"```bash\npython3 scripts/task.py handoff {first['id']}\n```"
        )
        also = [task for task in ready[1:]]
        if also:
            nxt += "\n\nAlso ready, so a second agent can take one:\n\n"
            nxt += "\n".join(
                f"- {task['id']} — `python3 scripts/task.py handoff {task['id']}`" for task in also
            )
    else:
        nxt = "Nothing is ready. See in-progress and blocked below."

    done_count = sum(task["status"] == "done" for task in data["tasks"])
    total = len(data["tasks"])
    parts = [
        "# NOW",
        "",
        "Read this file only, then run the command under **Next**.",
        "Do not scan the repository. Do not edit this file by hand.",
        "",
        "Project: Care Guide document intelligence (`docintel`).",
        f"Deadline: {data['deadline']}. Updated: {data.get('updated', 'unknown')}.",
        f"Progress: {done_count}/{total} tasks done.",
        "",
        "## Next",
        "",
        nxt,
        "",
        "## In progress",
        "",
        *lines_for("in_progress"),
        "",
        "## Blocked",
        "",
        *lines_for("blocked"),
        "",
        "## Ready",
        "",
        *lines_for("ready"),
        "",
        "## Done",
        "",
        *lines_for("done"),
        "",
        "## Rules",
        "",
        "1. Claim before you edit: `python3 scripts/task.py claim <ID> --agent <name>`.",
        "2. Read only the brief the handoff prints, plus the files that brief names.",
        "3. Finish with `python3 scripts/task.py done <ID> --agent <name> --note \"<one line>\"`.",
        "4. If you stop early: `python3 scripts/task.py block <ID> --agent <name> --note \"<what is left>\"`.",
        "5. One task per session. The stack is locked in `docs/DECISIONS.md`.",
        "",
    ]
    return "\n".join(parts)


def write_now(path: Path, data: dict) -> None:
    text = render_now(data)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def snapshot(data: dict) -> str:
    return json.dumps(data, sort_keys=True)


def apply(args: argparse.Namespace, mutate) -> dict:
    with locked(args.board):
        data = load(args.board)
        before = snapshot(data)
        promote(data)
        mutate(data)
        promote(data)
        if snapshot(data) != before:
            save(args.board, data)
        write_now(args.now, data)
        return data


def print_task(task: dict) -> None:
    print(f"{task['id']}  {task['status']:<12}  {task['estimate_min']:>3}m  {task['title']}")


def cmd_list(data: dict) -> None:
    for task in data["tasks"]:
        print_task(task)


def cmd_next(data: dict, show_all: bool) -> None:
    ready = [task for task in data["tasks"] if task["status"] == "ready"]
    if not ready:
        print("NOTHING_READY")
        for status in ("in_progress", "blocked"):
            chosen = [task for task in data["tasks"] if task["status"] == status]
            if not chosen:
                print(f"{status.upper()} none")
            for task in chosen:
                who = task.get("claimed_by") or ""
                print(f"{status.upper()} {task['id']} {who}".rstrip())
        done = {task["id"] for task in data["tasks"] if task["status"] == "done"}
        for task in data["tasks"]:
            if task["status"] == "pending":
                needed = [dep for dep in task["depends_on"] if dep not in done]
                print(f"WAITING {task['id']} needs {' '.join(needed)}")
        return
    chosen = ready if show_all else ready[:1]
    for task in chosen:
        print(
            f"NEXT {task['id']}  {task['title']}  estimate={task['estimate_min']}m  "
            f"brief={task['brief']}"
        )
        print(f"CLAIM python3 scripts/task.py claim {task['id']} --agent <name>")
    if not show_all and len(ready) > 1:
        rest = ", ".join(task["id"] for task in ready[1:])
        print(f"ALSO_READY {rest}")


def cmd_claim(data: dict, task_id: str, agent: str) -> None:
    task = require(data, task_id)
    if task["status"] != "ready":
        raise TaskError(f"{task_id} is {task['status']}, not ready")
    task["status"] = "in_progress"
    task["claimed_by"] = agent
    task["claimed_at"] = now_stamp()
    add_note(task, agent, "claimed")
    print(f"CLAIMED {task_id} by {agent}")


def cmd_release(data: dict, task_id: str, agent: str, note: str) -> None:
    task = require(data, task_id)
    if task["status"] != "in_progress":
        raise TaskError(f"{task_id} is {task['status']}, not in_progress")
    task["status"] = "pending"
    task["claimed_by"] = None
    task["claimed_at"] = None
    add_note(task, agent, note or "released")
    print(f"RELEASED {task_id}")


def cmd_done(data: dict, task_id: str, agent: str, note: str) -> None:
    if not note:
        raise TaskError("done requires --note")
    task = require(data, task_id)
    if task["status"] != "in_progress":
        raise TaskError(f"{task_id} is {task['status']}; claim it before done")
    task["status"] = "done"
    task["finished_at"] = now_stamp()
    add_note(task, agent, note)
    print(f"DONE {task_id}")


def cmd_block(data: dict, task_id: str, agent: str, note: str) -> None:
    if not note:
        raise TaskError("block requires --note")
    task = require(data, task_id)
    if task["status"] not in ("ready", "in_progress"):
        raise TaskError(f"{task_id} is {task['status']}; only ready or in_progress can block")
    task["status"] = "blocked"
    task["claimed_by"] = agent
    add_note(task, agent, note)
    print(f"BLOCKED {task_id}")


def cmd_unblock(data: dict, task_id: str, agent: str, note: str) -> None:
    task = require(data, task_id)
    if task["status"] != "blocked":
        raise TaskError(f"{task_id} is {task['status']}, not blocked")
    task["status"] = "pending"
    task["claimed_by"] = None
    add_note(task, agent, note or "unblocked")
    print(f"UNBLOCKED {task_id}")


def cmd_handoff(data: dict, root: Path, task_id: str | None) -> None:
    if task_id is None:
        ready = [task for task in data["tasks"] if task["status"] == "ready"]
        if not ready:
            raise TaskError("nothing is ready")
        task = ready[0]
    else:
        task = require(data, task_id)
        if task["status"] != "ready":
            raise TaskError(f"{task_id} is {task['status']}, not ready")
    brief = root / task["brief"]
    if not brief.is_file():
        raise TaskError(f"missing brief {brief}")
    body = brief.read_text().rstrip()
    owns = ", ".join(task["owns"])
    header = (
        f"Work only in {root}.\n"
        "Do this one task, then stop. Do not scan the repository.\n"
        "\n"
        "Rules\n"
        f"- Claim before any edit: python3 scripts/task.py claim {task['id']} --agent <name>\n"
        f"- Edit only the paths in \"Create or edit\". Owned paths: {owns}\n"
        "- Do not change the stack. Decisions are already locked.\n"
        f"- When the check command passes: python3 scripts/task.py done {task['id']} "
        '--agent <name> --note "<one line>"\n'
        f"- If you stop early: python3 scripts/task.py block {task['id']} "
        '--agent <name> --note "<what is left>"\n'
        "\n"
    )
    print(header + body + "\n")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Read or update the docintel task board.")
    parser.add_argument("--board", type=Path, default=ROOT / "board.json")
    parser.add_argument("--now", type=Path, default=ROOT / "NOW.md")
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("list", help="print every task")
    nxt = sub.add_parser("next", help="print the next ready task")
    nxt.add_argument("--all", action="store_true", help="print every ready task")

    def add_agent(command: argparse.ArgumentParser, note: bool = False, note_required: bool = False) -> None:
        command.add_argument("task_id")
        command.add_argument("--agent", required=True)
        if note:
            command.add_argument("--note", required=note_required, default="")

    add_agent(sub.add_parser("claim", help="mark a ready task in progress"))
    add_agent(sub.add_parser("release", help="return an in-progress task to ready"), note=True)
    add_agent(sub.add_parser("done", help="mark a task done and unlock dependents"), note=True, note_required=True)
    add_agent(sub.add_parser("block", help="stop a task with a reason"), note=True, note_required=True)
    add_agent(sub.add_parser("unblock", help="make a blocked task claimable again"), note=True)

    hand = sub.add_parser("handoff", help="print a self-contained prompt for one ready task")
    hand.add_argument("task_id", nargs="?")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.cmd == "list":
            data = apply(args, lambda _data: None)
            cmd_list(data)
        elif args.cmd == "next":
            data = apply(args, lambda _data: None)
            cmd_next(data, args.all)
        elif args.cmd == "claim":
            apply(args, lambda data: cmd_claim(data, args.task_id, args.agent))
        elif args.cmd == "release":
            apply(args, lambda data: cmd_release(data, args.task_id, args.agent, args.note))
        elif args.cmd == "done":
            apply(args, lambda data: cmd_done(data, args.task_id, args.agent, args.note))
        elif args.cmd == "block":
            apply(args, lambda data: cmd_block(data, args.task_id, args.agent, args.note))
        elif args.cmd == "unblock":
            apply(args, lambda data: cmd_unblock(data, args.task_id, args.agent, args.note))
        elif args.cmd == "handoff":
            data = apply(args, lambda _data: None)
            cmd_handoff(data, repo_root(args.board), args.task_id)
        else:
            raise TaskError(f"unknown command {args.cmd}")
    except TaskError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
